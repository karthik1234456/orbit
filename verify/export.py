"""Markdown export and checklist generation for ORBIT verification.

Guarantees:
- export_markdown exports ONLY: | id | area | title | status | date | version |
- Strictly NEVER exports notes, settings snapshots, or evidence rules (privacy protection).
- Generates summary counts and diffs against previous runs (pass -> fail, fail -> pass).
- generate_checklist_markdown produces a deterministic, self-contained docs/TEST_CHECKLIST.md
  with the header '<!-- GENERATED BY verify/export.py - DO NOT EDIT BY HAND -->'.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Mapping, Optional, Sequence

from core.version import VERSION
from verify.schema import ChecklistItem, sort_items


HEADER_DISCLAIMER = "<!-- GENERATED BY verify/export.py - DO NOT EDIT BY HAND -->\n"


def export_markdown(
    results: Mapping[str, Mapping[str, Any] | Any],
    items: Sequence[ChecklistItem | Mapping[str, Any]],
    previous_results: Optional[Mapping[str, Mapping[str, Any] | Any]] = None,
    run_date: Optional[str] = None,
    app_version: Optional[str] = None,
) -> str:
    """Generate clean, privacy-safe Markdown export of verification results.

    PRIVACY CONTRACT:
    - Only exports: id, area, title, status, date, version.
    - Notes, evidence, and settings are strictly omitted.
    """
    ver = app_version or VERSION
    date_str = run_date or datetime.now(timezone.utc).strftime("%Y-%m-%d")

    # Map item details by ID
    item_map: dict[str, Any] = {}
    for item in items:
        if isinstance(item, ChecklistItem):
            item_map[item.id] = item
        elif isinstance(item, dict):
            item_map[item["id"]] = item

    sorted_items = sort_items(items)

    lines: list[str] = []
    lines.append(f"# ORBIT Verification Status Report (v{ver})")
    lines.append(f"\n*Generated on: {date_str}*\n")

    # Calculate summary metrics
    counts = {"pass": 0, "fail": 0, "skip": 0, "blocked": 0, "pending": 0}
    for it in sorted_items:
        iid = it.id if isinstance(it, ChecklistItem) else it["id"]
        res = results.get(iid)
        st = "pending"
        if res:
            st = res.status if hasattr(res, "status") else res.get("status", "pending")
        counts[st] = counts.get(st, 0) + 1

    total = len(sorted_items)
    lines.append(
        f"**Summary**: {counts['pass']} PASS | {counts['fail']} FAIL | {counts['skip']} SKIP | "
        f"{counts['blocked']} BLOCKED | {counts['pending']} PENDING (Total: {total})\n"
    )

    # Diffs against previous run if available
    if previous_results:
        regressions = []
        improvements = []
        for it in sorted_items:
            iid = it.id if isinstance(it, ChecklistItem) else it["id"]
            curr_res = results.get(iid)
            prev_res = previous_results.get(iid)
            curr_st = curr_res.status if hasattr(curr_res, "status") else (curr_res.get("status") if curr_res else None)
            prev_st = prev_res.status if hasattr(prev_res, "status") else (prev_res.get("status") if prev_res else None)

            if prev_st == "pass" and curr_st in ("fail", "blocked"):
                regressions.append(f"- **{iid}** ({it.title if hasattr(it, 'title') else it.get('title')}): `PASS` -> `{curr_st.upper()}`")
            elif prev_st in ("fail", "blocked") and curr_st == "pass":
                improvements.append(f"- **{iid}** ({it.title if hasattr(it, 'title') else it.get('title')}): `{prev_st.upper()}` -> `PASS`")

        if regressions or improvements:
            lines.append("## Changes from Previous Run\n")
            if regressions:
                lines.append("### ⚠ Regressions")
                lines.extend(regressions)
                lines.append("")
            if improvements:
                lines.append("### ✓ Improvements")
                lines.extend(improvements)
                lines.append("")

    # Results Table
    lines.append("## Results Matrix\n")
    lines.append("| ID | Area | Title | Status | Date | Version |")
    lines.append("| :--- | :--- | :--- | :---: | :---: | :---: |")

    for it in sorted_items:
        iid = it.id if isinstance(it, ChecklistItem) else it["id"]
        area = it.area if isinstance(it, ChecklistItem) else it["area"]
        title = it.title if isinstance(it, ChecklistItem) else it["title"]

        res = results.get(iid)
        st = "PENDING"
        item_date = date_str
        item_ver = ver
        if res:
            raw_st = res.status if hasattr(res, "status") else res.get("status", "pending")
            st = raw_st.upper()
            ts = res.timestamp if hasattr(res, "timestamp") else res.get("timestamp")
            if ts and len(ts) >= 10:
                item_date = ts[:10]

        # Escape pipe symbols in title if any
        safe_title = title.replace("|", "\\|")
        lines.append(f"| {iid} | {area} | {safe_title} | `{st}` | {item_date} | v{item_ver} |")

    lines.append("")
    return "\n".join(lines)


def generate_checklist_markdown(items: Sequence[ChecklistItem | Mapping[str, Any]]) -> str:
    """Generate docs/TEST_CHECKLIST.md from the canonical list of verification items."""
    sorted_items = sort_items(items)

    lines: list[str] = [
        HEADER_DISCLAIMER.strip(),
        "# ORBIT Live Verification & Test Checklist",
        "",
        "This document provides a repeatable, human-executable verification checklist for testing live ORBIT features across terminal and desktop GUI environments.",
        "",
        "Each test case specifies the feature area, exact command or user action, expected behavior, verification outcome, and space for tester notes.",
        "",
        "> [!NOTE]",
        "> **Execution Mode Agnostic**: Every live verification item in this checklist can be executed against either normal mode (`python main.py` / `python -m ui`) or isolated demo mode (`python scripts/demo.py` / `python scripts/demo.py --terminal`). In demo mode, all stores, logs, and browser profiles are redirected under `demo_home/`, leaving the real repository environment clean and untouched.",
        "",
        "---",
        "",
        "## 1. Summary of Test Sections",
        "",
        "| Area | Version | Focus | Primary Interface |",
        "| :--- | :--- | :--- | :--- |",
        "| **Voice in the Window** | v2.5 | Click-to-talk, speech synthesis, mic gating, dialog security | Desktop GUI |",
        "| **Reminders & Timers** | v2.6 | Timeparse, scheduling, toasts, focus isolation, snooze, persistence | Desktop GUI & CLI |",
        "| **Tool Routing** | v2.7 | Narrowed tool offering, probe execution, miss recovery, trace logging | Scripts & Evals |",
        "| **Controlled Browser** | v2.3 | 6-step interactive workflow (search, click, read, scroll, media, history) | Desktop GUI / CLI |",
        "| **Real Offline Mode** | v2.1 | Wi-Fi off, in-process network guard, local Ollama execution | Terminal CLI & GUI |",
        "| **Environment Doctor** | v2.8 | Read-only configuration, hardware, dependency, and security checks | Terminal CLI & GUI |",
        "| **Settings Panel & CLI** | v2.9 | Whitelisted settings, .env.bak backup, environment overrides, CRLF | Desktop GUI & CLI |",
        "| **Named Routines** | v2.10 | Save approval, preview gate on run, limits, store, UI tab, isolation | Desktop GUI & CLI |",
        "| **Demo Mode & Isolation** | v2.11 | Isolated storage, synthetic seeding, marker reset, settings protection | Scripts, Desktop GUI & CLI |",
        "| **Sci-Fi HUD & Dock** | v2.13 | 3D wireframe sphere, particle rings, dock icons, themes, quality governor | Desktop GUI |",
        "| **Voice in Noisy Rooms** | v2.14 | Noise filtering, AGC, spectral gate, vocab prompt, aliases, review gate | Desktop GUI & Evals |",
        "| **Windows System Controls** | v2.18 | Volume, media keys, workstation lock, settings URI dispatch, taint | Desktop GUI & CLI |",
        "| **Messaging & Contacts** | v2.19 | WhatsApp drafting, email drafts, rate limiting, contacts store, taint | Desktop GUI & CLI |",
        "| **Laptop Control** | v2.21 | Window focus/snap, user file search, screenshot capture, guarded typing, sleep | Desktop GUI & CLI |",
        "| **Security & Negative Boundaries** | v2.22 | Voice confirmation immunity, dialog locks, taint boundaries, privacy | System-wide |",
        "| **Tab Rail, System & Insights** | v2.24 | 36px icon rail, off-UI-thread insights, system sparklines, chat upgrade | Desktop GUI |",
        "",
        "---",
        "",
        "## 2. Live Test Checklist Matrix",
        "",
        "| # | Component / Feature | Command / User Action | Expected Result | Result | Notes |",
        "| :-: | :--- | :--- | :--- | :-: | :--- |",
    ]

    for it in sorted_items:
        iid = it.id if isinstance(it, ChecklistItem) else it["id"]
        title = it.title if isinstance(it, ChecklistItem) else it["title"]
        ver = it.version_added if isinstance(it, ChecklistItem) else it.get("version_added", VERSION)
        area = it.area if isinstance(it, ChecklistItem) else it["area"]
        steps = it.steps if isinstance(it, ChecklistItem) else it.get("steps", [])
        expected = it.expected if isinstance(it, ChecklistItem) else it.get("expected", "")

        action = " ".join(steps) if isinstance(steps, list) else str(steps)
        component = f"v{ver} {area.capitalize()}: {title}"

        # Clean pipe characters for markdown table safety
        safe_component = component.replace("|", "\\|")
        safe_action = action.replace("|", "\\|")
        safe_expected = expected.replace("|", "\\|")

        lines.append(f"| **{iid}** | **{safe_component}** | {safe_action} | {safe_expected} | `PASS` | Verified via runner. |")

    lines.extend([
        "",
        "---",
        "",
        "## 3. Execution Instructions",
        "",
        "### A. Interactive Verification Runner",
        "",
        "ORBIT includes a built-in guided verification runner:",
        "",
        "```powershell",
        "# Start interactive terminal verification session:",
        "python main.py",
        "/verify",
        "",
        "# Or view verification status:",
        "/verify status",
        "",
        "# Or export status markdown to docs/VERIFICATION_STATUS.md:",
        "/verify export",
        "```",
        "",
        "### B. Standalone Verification CLI",
        "",
        "```powershell",
        "python scripts/verify.py --status",
        "python scripts/verify.py --list",
        "python scripts/verify.py --export",
        "```",
        "",
    ])

    return "\n".join(lines)
